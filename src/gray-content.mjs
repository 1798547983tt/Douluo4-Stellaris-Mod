// 仅选择展示资产；不改变g.form、战损、世界修订或资源。
export function resolveGrayArt(g,override='auto'){
  if(override==='wedding')return g?.weddingUnlocked===true?'wedding':'portrait';
  if(['portrait','ship','smile','battle','wave','serious','salute','reach'].includes(override))return override;
  if(g?.form==='战舰')return 'ship';
  if(g?.form==='重构')return 'ship';
  return g?.expression==='笑容'?'smile':g?.expression==='战意'?'battle':'portrait';
}
